#!/usr/bin/env python3
"""Message-accounting audit (v2) for a Dagster native-split UNSAT result.

Regenerates the region's split deterministically (dag_native_split.py with the recorded fixed
points, fixed transpositions and depth) and reads the exact interface-variable set from its DAG
file. Accept only if ALL hold:
  1. the number of distinct vertex-1 messages equals the split's message count M(D,k);
  2. every message assigns EXACTLY the interface variables, each once (one polarity each);
  3. every distinct message has at least one completion event;
  4. any worker holding a message at shutdown holds a copy of one completed elsewhere.
usage: audit_dagster.py <master.log.gz> --region RID --fixed "0 7 15 28" --depth K [--coords 1,2]
With --coords (the split coordinates recorded in the run's ledger) the interface is the set of
edge variables incident to them; without, the split is regenerated by the current rule.
       (legacy: audit_dagster.py <log> <D> <k> runs the v1 count-only checks)
"""
import argparse, gzip, os, re, subprocess, sys, tempfile
from itertools import combinations
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
VERSION = "audit-v2"
def M(D, k):
    t = 0
    for m in range(k // 2 + 1):
        w = sum(1 for P in combinations(list(combinations(range(k), 2)), m) if len({x for p in P for x in p}) == 2 * m)
        t += w * (D - (k - 1)) ** (k - 2 * m)
    return t
def expected_interface(fixed, trans, depth):
    with tempfile.TemporaryDirectory() as d:
        cmd = [sys.executable, f"{ROOT}/dag_native_split.py", ",".join(map(str, fixed)) or "-", d, "--depth", str(depth)]
        if trans: cmd += ["--fix-trans", ",".join(f"{a}-{b}" for a, b in trans)]
        subprocess.run(cmd, check=True, capture_output=True)
        g = open(f"{d}/dag_split.dag").read()
        import json; meta = json.load(open(f"{d}/split_meta.json"))
    ivars = {int(v) for v in re.search(r"0->1:([\d,]+)", g).group(1).split(",")}
    return ivars, meta
def interface_from_coords(fixed, coords):
    """The interface a run actually used: every edge variable incident to its recorded split
    coordinates, numbered by the same deterministic generator."""
    sys.path.insert(0, ROOT)
    from gen_sym32_v2 import build
    Fb, nv, var, cl, rep, edge = build(list(fixed))
    iv = {v for (a, b), v in edge.items() if a in coords or b in coords}
    D = len(next(iter([[v for (a, b), v in edge.items() if coords[0] in (a, b)]])))
    return iv, D

def scan(log):
    rx = re.compile(r"^[IWEF](?:\d{8}|\d{4}) ")
    cur, done, keys = {}, set(), set()
    for l in gzip.open(log, "rt"):
        if not rx.match(l): continue
        a = re.search(r"sending message to worker (\d+) message about node (\d+) assignments:(.*)$", l)
        if a:
            key = tuple(sorted(int(x) for x in re.findall(r"-?\d+", a.group(3)))) if a.group(2) == "1" else None
            if key is not None: keys.add(key)
            cur[a.group(1)] = key; continue
        b = re.search(r"received MPI_TAG_REQUEST_FOR_ASSIGNMENT from worker (\d+)", l)
        if b and b.group(1) in cur:
            key = cur.pop(b.group(1))
            if key is not None: done.add(key)
    return keys, done, [k for k in cur.values() if k is not None]
def audit(log, fixed, trans, depth, coords=None):
    """coords: the split coordinates the run recorded (preferred). Without them the split is
    regenerated with the current coordinate rule."""
    rule_coords = None
    if coords:
        ivars, D = interface_from_coords(fixed, coords); meta = {"coords": coords}
    else:
        ivars, meta = expected_interface(fixed, trans, depth); D = meta["domains"][0]
    exp = M(D, depth)
    keys, done, held = scan(log)
    bad_iface = [k for k in keys if {abs(v) for v in k} != ivars or len(k) != len(ivars)]
    checks = [("distinct messages == M(D,k)", len(keys) == exp, f"{len(keys)} vs {exp}"),
              ("exact interface variables, one literal each", not bad_iface and bool(keys),
               f"{len(keys)-len(bad_iface)}/{len(keys)} messages match the {len(ivars)}-variable interface"),
              ("every message completed", keys <= done, f"{len(keys & done)}/{len(keys)} completed"),
              ("shutdown holds only completed copies", all(k in done for k in held), f"{len(held)} held at shutdown")]
    return all(c[1] for c in checks), checks, {"coords": meta["coords"], "interface": len(ivars), "expected": exp}
if __name__ == "__main__":
    if len(sys.argv) == 4 and not sys.argv[2].startswith("--"):
        sys.exit("legacy v1 mode removed: use --region/--fixed/--depth (see --help)")
    ap = argparse.ArgumentParser(); ap.add_argument("log"); ap.add_argument("--region", required=True)
    ap.add_argument("--fixed", default=""); ap.add_argument("--depth", type=int, required=True)
    ap.add_argument("--coords", default="", help="the run's recorded split coordinates, e.g. 1,2")
    a = ap.parse_args()
    case = a.region.partition("@")[2]
    trans = [tuple(sorted(map(int, t.split("-")))) for t in case.split(",") if t]
    co = [int(x) for x in a.coords.split(",") if x]
    ok, checks, info = audit(a.log, [int(x) for x in a.fixed.split()], trans, a.depth, co or None)
    for n, c, why in checks: print(f"  {'PASS' if c else 'FAIL'}  {n:<44} {why}")
    print(f"{VERSION}: {'AUDIT PASS' if ok else 'AUDIT FAIL'}  coords={info['coords']}"); sys.exit(0 if ok else 1)
